/**
 * Pure report rendering for `npm run verify` — no I/O, so it is unit-tested
 * (tests/verify-report.test.ts) and cannot fail on the owner's machine.
 */
import type {Requirement} from './verify-plan';

export type Status='PASS'|'FAIL'|'NOT TESTED';

export type ItemResult={status:Status;evidence:string};

export type StepRecord={ref:string;label:string;status:Status;evidence:string;logTail?:string};

export type ReportInput={
  milestone:string;
  requirements:Requirement[];
  /** Keyed by requirement id. A missing key is reported as NOT TESTED (never silently PASS). */
  results:Record<string,ItemResult>;
  steps:StepRecord[];
  env:{node:string;npm:string;platform:string;hostname?:string};
  startedAt:string;
  finishedAt:string;
  durationMs:number;
  screenshots:{dir:string;files:string[]};
  notes?:string[];
};

export type Summary={pass:number;fail:number;notTested:number;total:number};

export function summarize(requirements:Requirement[],results:Record<string,ItemResult>):Summary{
  const s:Summary={pass:0,fail:0,notTested:0,total:requirements.length};
  for(const r of requirements){
    const status=results[r.id]?.status||'NOT TESTED';
    if(status==='PASS')s.pass++;else if(status==='FAIL')s.fail++;else s.notTested++;
  }
  return s;
}

/** One word for the whole run. INCOMPLETE means "nothing failed, but not everything was proven". */
export function overallStatus(s:Summary):'PASS'|'FAIL'|'INCOMPLETE'{
  if(s.fail>0)return 'FAIL';
  if(s.notTested>0)return 'INCOMPLETE';
  return 'PASS';
}

/** Non-zero only when something actually failed, so "INCOMPLETE" does not look like a crash. */
export function exitCodeFor(s:Summary):number{return s.fail>0?1:0}

const badge=(status:Status):string=>status==='PASS'?'✅ PASS':status==='FAIL'?'❌ FAIL':'⚠️ NOT TESTED';

/** One line per requirement, exactly as the owner asked: PASS / FAIL / NOT TESTED and why. */
export function requirementRows(requirements:Requirement[],results:Record<string,ItemResult>):string[]{
  const rows:string[]=['| ID | Requirement · প্রয়োজনীয়তা | Result | Evidence, or why it was not tested |','| --- | --- | --- | --- |'];
  for(const r of requirements){
    const item=results[r.id];
    const status=item?.status||'NOT TESTED';
    const why=item?.evidence||'No result was recorded for this requirement.';
    const cell=`${r.text}<br><sub>${r.bn}</sub>`;
    rows.push(`| ${r.id} | ${cell} | ${badge(status)} | ${escapeCell(why)} |`);
  }
  return rows;
}

function escapeCell(text:string):string{return text.replace(/\|/g,'\\|').replace(/\r?\n/g,'<br>')}

export function renderReport(input:ReportInput):string{
  const s=summarize(input.requirements,input.results);
  const overall=overallStatus(s);
  const seconds=Math.round(input.durationMs/1000);
  const lines:string[]=[];
  lines.push(`# Verification report — milestone ${input.milestone}`);
  lines.push('');
  lines.push(`Generated by \`npm run verify\` on ${input.finishedAt} (started ${input.startedAt}, took ${seconds}s).`);
  lines.push(`Machine: ${input.env.platform} · Node ${input.env.node} · npm ${input.env.npm}${input.env.hostname?` · ${input.env.hostname}`:''}`);
  lines.push('');
  lines.push(`## Result: **${overall}** — ${s.pass} PASS, ${s.fail} FAIL, ${s.notTested} NOT TESTED (of ${s.total} requirements)`);
  lines.push('');
  lines.push(overall==='PASS'
    ? 'Every requirement for this milestone was demonstrated on this machine. This build can be called **verified**.'
    : overall==='FAIL'
      ? 'At least one requirement failed. Send `verify-output.zip` back — the failing evidence line says which one.'
      : 'Nothing failed, but some requirements could not be proven here. Each NOT TESTED line says why and what would make it run.');
  lines.push('');
  lines.push('## Requirements');
  lines.push('');
  lines.push(...requirementRows(input.requirements,input.results));
  lines.push('');
  lines.push('## Steps that produced the evidence');
  lines.push('');
  lines.push('| Step | Result | Evidence |','| --- | --- | --- |');
  for(const step of input.steps)lines.push(`| ${step.label} | ${badge(step.status)} | ${escapeCell(step.evidence)} |`);
  lines.push('');
  lines.push('## Screenshots');
  lines.push('');
  lines.push(input.screenshots.files.length
    ? `${input.screenshots.files.length} image(s) in \`${input.screenshots.dir}\` — each page at 360 px (mobile) and 1440 px (desktop).`
    : `No screenshots were captured. Directory would have been \`${input.screenshots.dir}\`.`);
  if(input.screenshots.files.length){
    lines.push('');
    for(const f of input.screenshots.files)lines.push(`- \`${f}\``);
  }
  lines.push('');
  lines.push('## What to send back');
  lines.push('');
  lines.push('1. `verify-output.zip` (this report, the screenshots and the raw step logs).');
  lines.push('2. If something failed: the exact line from the table above, plus anything you saw on screen.');
  lines.push('');
  if(input.notes?.length){
    lines.push('## Notes');
    lines.push('');
    for(const n of input.notes)lines.push(`- ${n}`);
    lines.push('');
  }
  lines.push('---');
  lines.push('');
  lines.push('Status words used in this project: **code complete, awaiting owner verification** until a run like this one comes back all PASS; **verified** only after that. Never "done" on unit tests alone.');
  lines.push('');
  return lines.join('\n');
}
